    static double storm(long seed, int octaves, double x, double min, double max) {
        return min + (fold(seed, octaves, x) - FOLD_LOW) * ((max - min) / (FOLD_HIGH - FOLD_LOW));
    }

    private static double fold(long seed, int octaves, double x) {
        float bounding = BOUNDING[octaves];
        float shrink = 1 << (octaves - 1);
        double skew = x * SKEW;
        double skewedX = x + skew;
        int warpSeed = (int) (seed ^ seed >> 32);
        float amp = WARP_AMP * bounding;
        float frequency = WARP_FREQUENCY / shrink;
        warpX = x;
        warpY = 0.0;
        for (int i = 0; i < octaves; i++) {
            warp(warpSeed + i, amp * WARP_GAIN, frequency, skewedX, skew);
            amp *= 0.5F;
            frequency *= 2F;
        }

        long next = seed + 1L;
        int baseSeed = (int) (next ^ next >> 32);
        frequency = BASE_FREQUENCY / shrink;
        double bx = warpX * frequency;
        double by = warpY * frequency;
        double shift = (bx + by) * SKEW;
        bx += shift;
        by += shift;
        float sum = 0F;
        float weight = bounding;
        for (int i = 0; i < octaves; i++) {
            sum += simplex(baseSeed + i, bx, by) * weight;
            bx *= 2.0;
            by *= 2.0;
            weight *= 0.5F;
        }
        double v = sum;
        return v > FOLD_AT ? v - FOLD_HIGH : -v;
    }

    private static float simplex(int seed, double x, double y) {
        int i = floor(x);
        int j = floor(y);
        float xi = (float) (x - i);
        float yi = (float) (y - j);
        i *= PRIME_X;
        j *= PRIME_Y;
        float t = (xi + yi) * 0.21132487F;
        float x0 = xi - t;
        float y0 = yi - t;

        float a0 = 0.6666667F - x0 * x0 - y0 * y0;
        float value = a0 * a0 * a0 * a0 * gradient(seed, i, j, x0, y0);
        float a1 = 3.1547005F * t - 0.6666667F + a0;
        value += a1 * a1 * a1 * a1 * gradient(seed, i + PRIME_X, j + PRIME_Y, x0 - 0.57735026F, y0 - 0.57735026F);

        float xmyi = xi - yi;
        if (t > 0.21132486540518713) {
            if (xi + xmyi > 1F) {
                value += corner(seed, i + (PRIME_X << 1), j + PRIME_Y, x0 - 1.3660254F, y0 - 0.36602542F);
            } else {
                value += corner(seed, i, j + PRIME_Y, x0 + 0.21132487F, y0 - 0.7886751F);
            }
            if (yi - xmyi > 1F) {
                value += corner(seed, i + PRIME_X, j + (PRIME_Y << 1), x0 - 0.36602542F, y0 - 1.3660254F);
            } else {
                value += corner(seed, i + PRIME_X, j, x0 - 0.7886751F, y0 + 0.21132487F);
            }
        } else {
            if (xi + xmyi < 0F) {
                value += corner(seed, i - PRIME_X, j, x0 + 0.7886751F, y0 - 0.21132487F);
            } else {
                value += corner(seed, i + PRIME_X, j, x0 - 0.7886751F, y0 + 0.21132487F);
            }
            if (yi < xmyi) {
                value += corner(seed, i, j - PRIME_Y, x0 - 0.21132487F, y0 + 0.7886751F);
            } else {
                value += corner(seed, i, j + PRIME_Y, x0 + 0.21132487F, y0 - 0.7886751F);
            }
        }
        return value * 18.241962F;
    }

    private static float corner(int seed, int xPrimed, int yPrimed, float xd, float yd) {
        float a = 0.6666667F - xd * xd - yd * yd;
        return a > 0F ? a * a * a * a * gradient(seed, xPrimed, yPrimed, xd, yd) : 0F;
    }

    private static float gradient(int seed, int xPrimed, int yPrimed, float xd, float yd) {
        int hash = hash(seed, xPrimed, yPrimed);
        hash ^= hash >> 15;
        hash &= 254;
        return xd * GRADIENTS[hash] + yd * GRADIENTS[hash | 1];
    }

    private static void warp(int seed, float amp, float frequency, double x, double y) {
        x *= frequency;
        y *= frequency;
        int i = floor(x);
        int j = floor(y);
        float xi = (float) (x - i);
        float yi = (float) (y - j);
        float t = (xi + yi) * 0.21132487F;
        float x0 = xi - t;
        float y0 = yi - t;
        i *= PRIME_X;
        j *= PRIME_Y;
        float vx = 0F;
        float vy = 0F;

        float a0 = 0.5F - x0 * x0 - y0 * y0;
        if (a0 > 0F) {
            float w = a0 * a0 * a0 * a0;
            int hash = hash(seed, i, j);
            float g = warpGradient(hash, x0, y0);
            int v = hash >> 7 & 510;
            vx += w * (g * VECTORS[v]);
            vy += w * (g * VECTORS[v | 1]);
        }

        float a1 = 3.1547005F * t - 0.6666666F + a0;
        if (a1 > 0F) {
            float x1 = x0 - 0.57735026F;
            float y1 = y0 - 0.57735026F;
            float w = a1 * a1 * a1 * a1;
            int hash = hash(seed, i + PRIME_X, j + PRIME_Y);
            float g = warpGradient(hash, x1, y1);
            int v = hash >> 7 & 510;
            vx += w * (g * VECTORS[v]);
            vy += w * (g * VECTORS[v | 1]);
        }

        float x2;
        float y2;
        int xPrimed;
        int yPrimed;
        if (y0 > x0) {
            x2 = x0 + 0.21132487F;
            y2 = y0 - 0.7886751F;
            xPrimed = i;
            yPrimed = j + PRIME_Y;
        } else {
            x2 = x0 - 0.7886751F;
            y2 = y0 + 0.21132487F;
            xPrimed = i + PRIME_X;
            yPrimed = j;
        }
        float a2 = 0.5F - x2 * x2 - y2 * y2;
        if (a2 > 0F) {
            float w = a2 * a2 * a2 * a2;
            int hash = hash(seed, xPrimed, yPrimed);
            float g = warpGradient(hash, x2, y2);
            int v = hash >> 7 & 510;
            vx += w * (g * VECTORS[v]);
            vy += w * (g * VECTORS[v | 1]);
        }

        warpX += vx * amp;
        warpY += vy * amp;
    }

    private static float warpGradient(int hash, float xd, float yd) {
        int index = hash & 254;
        return xd * GRADIENTS[index] + yd * GRADIENTS[index | 1];
    }

    private static int hash(int seed, int xPrimed, int yPrimed) {
        return (seed ^ xPrimed ^ yPrimed) * HASH_MULTIPLIER;
    }

    private static int floor(double f) {
        return f >= 0.0 ? (int) f : (int) f - 1;
    }
